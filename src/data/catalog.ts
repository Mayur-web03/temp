function via(
  a: { lat: number; lng: number },
  b: { lat: number; lng: number },
  bends: Array<[number, number]>,
) {
  return [
    a,
    ...bends.map(([t, o]) => ({
      lat: a.lat + (b.lat - a.lat) * t + o * 0.04,
      lng: a.lng + (b.lng - a.lng) * t + o * 0.05,
    })),
    b,
  ];
}

